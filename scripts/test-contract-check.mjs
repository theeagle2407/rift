import assert from 'node:assert/strict';
import {matchesIncrement,contractCheck} from '../src/lib/rift/contract-check.ts';
const now=Date.parse('2026-09-27T20:00:00Z');
const snapshot={instrument:{symbol:'NVDAUSDT',name:'NVIDIA',baseCoin:'NVDA',terms:{minOrderQty:'0.01',quantityMultiplier:'0.01',minOrderAmount:'5'}},fetchedAt:new Date(now).toISOString(),source:'fixture'};
const check=(q,p='225',s=snapshot,time=now)=>contractCheck(s,'NVDAUSDT',q,p,time);
assert.equal(matchesIncrement('0.30','0.1'),true);
assert.equal(matchesIncrement('11.875','0.01'),false);
assert.equal(matchesIncrement('0.010','0.01'),true);
assert.equal(matchesIncrement('1e2','0.01'),null);
assert.equal(check('10').status,'checked');
assert.equal(check('11.875').status,'mismatch');
assert.equal(check('0.01').status,'mismatch');
assert.equal(check('0.001','10000').status,'mismatch');
assert.equal(check('1','5').status,'checked');
assert.equal(check('1','4.999999999999999999').status,'mismatch');
assert.equal(check('10','225',null).status,'unavailable');
assert.equal(check('10','225',snapshot,now+300001).status,'stale');
assert.equal(check('10','225',snapshot,now-1).status,'stale');
assert.equal(check('10','225',{...snapshot,instrument:{...snapshot.instrument,symbol:'TSLAUSDT'}}).status,'unavailable');
assert.equal(check('10','225',{...snapshot,instrument:{...snapshot.instrument,terms:{}}}).status,'unavailable');
console.log('PASS 15 contract checks: decimals, minimums, missing data, wrong symbol and stale rules');
